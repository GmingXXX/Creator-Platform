async function openEditor(page: Page, id = 'work-1') {
  await page.goto('/#/login');
  await page.getByRole('button', { name: '填入', exact: true }).click();
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page.getByRole('heading', { name: '您想创建什么？' })).toBeVisible();
  await page.goto(`/#/editor/${id}`);
  await expect(page.locator('.scene-board')).toBeVisible();
}

test('画布移动缩放、手势撤销、结构编辑、运行和刷新恢复', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await openEditor(page);
  await page.screenshot({ path: 'output/验收截图/editor-initial-1440.png' });
  const heading = page.locator('.node-hitbox').nth(1);
  await heading.click();
  const x = page.getByRole('spinbutton', { name: 'X', exact: true });
  const oldX = Number(await x.inputValue());
  const bounds = (await heading.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width * .3, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .3 + 40, bounds.y + bounds.height / 2 + 20, { steps: 8 });
  await page.mouse.up();
  const movedX = Number(await x.inputValue());
  expect(movedX).toBeGreaterThan(oldX);
  await page.getByTitle('撤销（⌘Z）').click();
  await expect(x).toHaveValue(String(oldX));
  await page.getByTitle('重做（⌘⇧Z）').click();
  await expect(x).toHaveValue(String(movedX));
  const width = page.getByRole('spinbutton', { name: 'W', exact: true });
  const oldWidth = Number(await width.inputValue());
  const handle = (await page.locator('.node-hitbox.selected .handle-se').boundingBox())!;
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down();
  await page.mouse.move(handle.x + 50, handle.y + 20, { steps: 6 });
  await page.mouse.up();
  expect(Number(await width.inputValue())).toBeGreaterThan(oldWidth);
  await page.getByTitle('撤销（⌘Z）').click();
  await page.getByTitle('撤销（⌘Z）').click();
  await page.getByRole('button', { name: '左对齐', exact: true }).click();
  await expect(page.locator('.editor-document')).toContainText('所有更改已保存');
  await page.getByRole('button', { name: '分享投稿', exact: true }).click();
  await page.getByRole('button', { name: '提交审核', exact: true }).focus();
  await page.keyboard.press('Delete');
  await expect(page.locator('.node-hitbox')).toHaveCount(5);
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
  await page.locator('.node-hitbox').nth(3).dblclick();
  await page.getByRole('textbox', { name: '条目标题' }).first().fill('验收 · 真实内容修改');
  await page.getByRole('button', { name: '添加条目', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '条目标题' })).toHaveCount(6);
  await page.getByRole('button', { name: '运行预览', exact: true }).first().click();
  await page.locator('.runtime-overlay .timeline-event').first().click();
  await expect(page.locator('.scene-detail')).toContainText('验收 · 真实内容修改');
  await page.screenshot({ path: 'output/验收截图/editor-runtime-detail-1440.png' });
  await page.getByRole('button', { name: '关闭详情' }).click();
  await page.getByRole('button', { name: /返回编辑/ }).click();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.screenshot({ path: 'output/验收截图/editor-edited-1440.png' });
  await reloadAndReopen(page);
  await expect(page.locator('.scene-board .scene-renderer')).toContainText('验收 · 真实内容修改');
  expect(errors).toEqual([]);
});


import {expect,test} from '@playwright/test';

test('输入框直接移除参考、附件、技能和资料包，保留原资源与输入',async({page})=>{
 await page.route('**/api/ai/**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({models:[{id:'demo',label:'演示'}],configured:{}})}));
 await page.goto('/#/login');
 await page.getByRole('button',{name:'填入',exact:true}).click();
 await page.getByRole('button',{name:'进入工作台',exact:true}).click();
 await expect(page.getByLabel('创作需求',{exact:true})).toBeVisible();
 await page.evaluate(()=>{
  const data=JSON.parse(localStorage.getItem('zhichuang-studio-v1')!);
  const draft=data.state.drafts.find((d:any)=>d.id===data.state.activeDraftId);
  draft.text='保留这段创作需求';
  draft.attachmentIds=['remove-attachment'];
  data.state.assets.push({id:'remove-attachment',name:'测试客户资料.txt',kind:'document',workspaceId:'personal',source:'uploaded',public:false,src:'',tags:[],description:'',author:'测试',createdAt:new Date().toISOString()});
  draft.skillIds=[data.state.skills[0].id];
  draft.reference={id:'remove-package',version:'1.0',prompt:'参考说明',params:{},files:[],skillIds:[],complete:true};
  localStorage.setItem('zhichuang-studio-v1',JSON.stringify(data));
 });
 await page.reload();
 await page.getByRole('button',{name:'创作参考',exact:true}).click();
 const picker=page.getByRole('dialog',{name:'添加参考展项',exact:true});
 const option=picker.locator('.reference-source-card').first();
 const value=await option.getAttribute('data-reference-source');
 await option.locator('.reference-source-select').click();
 await picker.getByRole('checkbox',{name:'UI 风格',exact:true}).check();
 await picker.getByRole('button',{name:'加入参考',exact:true}).click();
 const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('zhichuang-studio-v1')!).state);
 await expect(page.getByTestId('exhibit-reference-summary')).toHaveCount(1);
 await page.screenshot({path:'output/qa-scope-cards-composer.png'});
 await page.locator('.reference-summary').getByRole('button',{name:/移除创作参考/}).click();
 await expect(page.getByTestId('exhibit-reference-summary')).toHaveCount(0);
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'创作参考',exact:true})).not.toContainText('·');
 await page.getByRole('button',{name:'移除 测试客户资料.txt',exact:true}).click();
 await page.getByRole('button',{name:/移除技能 /}).click();
 await page.getByRole('button',{name:'移除参考资料包',exact:true}).click();
 await expect(page.locator('.composer-context')).toHaveCount(0);
 await expect(page.getByLabel('创作需求',{exact:true})).toHaveValue('保留这段创作需求');
 await page.reload();
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('zhichuang-studio-v1')!).state);
 const draft=after.drafts.find((d:any)=>d.id===after.activeDraftId);
 expect(draft.references).toEqual([]);expect(draft.attachmentIds).toEqual([]);expect(draft.skillIds).toEqual([]);
 expect(after.assets).toEqual(before.assets);expect(after.works).toEqual(before.works);expect(after.skills).toEqual(before.skills);
 await page.goto('/#/editor/work-1');
 await page.getByRole('button',{name:'打开 Agent 助手',exact:true}).click();
 await page.getByRole('button',{name:'创作参考',exact:true}).click();
 await page.locator(`[data-reference-source="${value}"] .reference-source-select`).click();
 await page.getByRole('button',{name:'加入参考',exact:true}).click();
 await page.locator('.reference-summary').getByRole('button',{name:/移除创作参考/}).click();
 await expect(page.getByTestId('exhibit-reference-summary')).toHaveCount(0);
 const edited=await page.evaluate(()=>JSON.parse(localStorage.getItem('zhichuang-studio-v1')!).state.works.find((w:any)=>w.id==='work-1'));
 expect(edited.references).toEqual([]);
 expect(edited.pages).toEqual(after.works.find((w:any)=>w.id==='work-1').pages);
});

import {reloadAndReopen} from './reload-helpers';
import { test, expect, type Page } from '@playwright/test';
import type { StudioData } from '../../src/domain/types';

const errors = new WeakMap<Page, string[]>();
const readState = (page: Page): Promise<StudioData> => page.evaluate(() => JSON.parse(localStorage.getItem('zhichuang-studio-v1')!).state);
const card = (page: Page, title: string) => page.locator('.res-project-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) });

test.beforeEach(async ({ page }) => {
  errors.set(page, []);
  page.on('pageerror', error => errors.get(page)?.push(error.message));
  await page.goto('/#/login');
  await page.getByRole('button', { name: '填入', exact: true }).click();
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page.getByRole('textbox', { name: '创作需求', exact: true })).toBeVisible();
});
test.afterEach(async ({ page }) => { expect(errors.get(page)).toEqual([]); });

test('新建演示归项目，继续编辑更新同一工程及真实页面预览', async ({ page }) => {
  const title = '演示项目归属验收';
  await page.goto('/#/presentations');
  await expect(page).toHaveURL(/#\/projects\?category=presentation-video$/);
  await page.locator('.sidebar').getByRole('button',{name:'新建作品',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'智能演示',exact:true}).click();
  await page.getByLabel('你想讲述什么？', { exact: true }).fill(title);
  await page.getByLabel('生成模型',{exact:true}).selectOption('demo');
  await page.getByRole('button', { name: '生成大纲', exact: true }).click();
  await page.getByRole('button', { name: '创建并进入编辑器', exact: true }).click();
  await expect(page).toHaveURL(/#\/presentations\//);
  const original = (await readState(page)).works.find(work => work.title === title)!;
  await page.getByRole('button', { name: '查看作品', exact: true }).click();
  await expect(card(page, title)).toBeVisible();
  await card(page,title).getByRole('button',{name:`打开${title}`,exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`/presentations/${original.id}$`));
  await page.locator('.slide-edit-stage .slide-element').first().click();
  await page.getByLabel('文字内容', { exact: true }).fill('从项目继续编辑的新内容');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '查看作品', exact: true }).click();
  await card(page,title).getByRole('button',{name:`${title}更多操作`,exact:true}).click();
  await page.getByRole('menuitem',{name:'预览作品',exact:true}).click();
  await expect(page.getByTestId('presentation-material-preview')).toContainText('从项目继续编辑的新内容');
  await page.goto('/#/projects?category=presentation-video');
  await reloadAndReopen(page);
  await expect(card(page,title)).toHaveCount(1);
  expect((await readState(page)).assets.filter(asset=>asset.sourceWorkId===original.id)).toHaveLength(0);
  await page.screenshot({ path: 'output/验收截图/v14-presentation-projects.png', fullPage: true, animations: 'disabled' });
  await page.goto('/#/library');
  await expect(page.getByRole('heading',{name:title,exact:true})).toHaveCount(0);
  await page.setViewportSize({width:1024,height:768});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'output/验收截图/v14-materials-1024.png',fullPage:true,animations:'disabled'});
});

test('视频项目预览当前分镜，删除和恢复保留原工程', async ({ page }) => {
  await page.goto('/#/video/work-5');
  await page.getByLabel('分镜标题', { exact: true }).fill('项目同步的最新镜头');
  await page.getByLabel('讲述文案', { exact: true }).fill('此字幕来自最新保存的原始视频工程。');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '查看作品', exact: true }).click();
  const work=(await readState(page)).works.find(item=>item.id==='work-5')!;
  await card(page,work.title).getByRole('button',{name:`${work.title}更多操作`,exact:true}).click();
  await page.getByRole('menuitem',{name:'预览作品',exact:true}).click();
  await expect(page.getByTestId('video-material-preview')).toContainText('此字幕来自最新保存的原始视频工程。');
  await expect(page.getByTestId('video-material-preview')).toContainText('完整视频尚未合成');
  await page.getByRole('button', { name: '播放分镜', exact: true }).click();
  await expect(page.getByRole('button', { name: '暂停分镜', exact: true })).toBeVisible();
  const media=page.getByTestId('video-material-preview').locator('video');
  await expect.poll(()=>media.evaluate(element=>(element as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2);
  await expect.poll(()=>media.evaluate(element=>(element as HTMLVideoElement).currentTime)).toBeGreaterThan(.1);
  await page.screenshot({path:'output/验收截图/v14-video-project-preview.png',animations:'disabled'});
  await page.goto('/#/projects?category=presentation-video');
  await card(page,work.title).getByRole('button',{name:`${work.title}更多操作`,exact:true}).click();
  await expect(page.getByRole('menuitem',{name:'归档作品',exact:true})).toHaveCount(0);
  await page.getByRole('menuitem',{name:'删除作品',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'移入回收站',exact:true}).click();
  await page.getByRole('button',{name:/回收站/}).click();
  await card(page,work.title).getByRole('button',{name:'恢复作品',exact:true}).click();
  await page.getByRole('button',{name:/全部作品/}).click();
  await card(page,work.title).getByRole('button',{name:`打开${work.title}`,exact:true}).click();
  await expect(page).toHaveURL(/#\/video\/work-5$/);
  await expect(page.getByLabel('分镜标题',{exact:true})).toHaveValue('项目同步的最新镜头');
  expect((await readState(page)).works.find(item=>item.id==='work-5')!.shots).toEqual(work.shots);
});

test('发布演示模板保持审核快照，社区复用生成独立可编辑工程', async ({ page }) => {
  const original=(await readState(page)).works.find(work=>work.id==='work-4')!;
  await page.goto('/#/projects?category=presentation-video');
  await card(page,original.title).getByRole('button',{name:`${original.title}更多操作`,exact:true}).click();
  await page.getByRole('menuitem',{name:'提交到共创社区',exact:true}).click();
  await page.getByLabel('投稿标题',{exact:true}).fill('演示模板快照验收');
  await page.getByRole('group',{name:'展示内容',exact:true}).getByRole('button',{name:'案例成果',exact:true}).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'提交审核',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto('/#/review');
  await page.getByRole('button',{name:'演示：切换为审核员',exact:true}).click();
  await page.locator('.res-review-row').filter({hasText:'演示模板快照验收'}).click();
  for(const checkbox of await page.locator('.res-review-checks input').all())await checkbox.check();
  await page.getByRole('button',{name:'通过并发布',exact:true}).click();
  await page.goto('/#/presentations/work-4');
  await page.locator('.slide-edit-stage .slide-element').first().click();
  await page.getByLabel('文字内容',{exact:true}).fill('发布之后的私有修改');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.goto('/#/community?tab=templates&category=presentation-video');
  await page.getByRole('button',{name:'预览演示模板快照验收',exact:true}).click();
  await expect(page.getByTestId('presentation-material-preview')).not.toContainText('发布之后的私有修改');
  await page.getByRole('dialog').getByRole('button',{name:'快速复用并编辑',exact:true}).click();
  await expect(page).toHaveURL(/#\/presentations\//);
  const copiedId=page.url().split('/').at(-1)!;
  expect(copiedId).not.toBe(original.id);
  const after=await readState(page),copy=after.works.find(work=>work.id===copiedId)!;
  expect(copy.pages[0].nodes.map(node=>node.content)).toEqual(original.pages[0].nodes.map(node=>node.content));
  expect(after.works.find(work=>work.id===original.id)!.pages[0].nodes[0].content).toBe('发布之后的私有修改');
  expect(after.assets.filter(asset=>asset.sourceWorkId===copiedId)).toHaveLength(0);
});

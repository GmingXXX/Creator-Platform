import {reloadAndReopen} from './reload-helpers';
import { test, expect, type Page } from '@playwright/test';

const pixel = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jE0cAAAAASUVORK5CYII=', 'base64');
async function space(page: Page, name: string) {
  await page.getByRole('button', { name: '切换创作空间' }).click();
  await page.getByRole('menuitem', { name, exact: true }).click();
}

test('personal materials require explicit project import while project uploads remain isolated', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#/login');
  await page.getByLabel('账号', { exact: true }).fill('jiming');
  await page.getByLabel('密码', { exact: true }).fill('123456');
  await page.getByRole('button', { name: '进入工作台' }).click();
  await expect(page).toHaveURL(/#\/$/);
  await space(page, '信泰企业展厅');
  await page.getByRole('link', { name: '素材库', exact: true }).click();
  await expect(page.getByRole('tab',{name:'空间共享',exact:true})).toHaveAttribute('aria-selected','true');
  await page.getByRole('tab',{name:'我的素材',exact:true}).click();
  await page.getByRole('button', { name: '上传素材', exact: true }).first().click();
  await page.locator('input[type=file]').setInputFiles({ name: '信泰项目参考.png', mimeType: 'image/png', buffer: pixel });
  await expect(page.getByText('已添加', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await expect(page.getByRole('button', { name: '预览信泰项目参考.png', exact: true })).toBeVisible();
  await page.getByRole('button',{name:'信泰项目参考.png更多操作',exact:true}).click();
  await page.getByRole('menuitem',{name:'带入当前空间',exact:true}).click();
  await page.getByRole('button',{name:'确认带入',exact:true}).click();
  await page.getByRole('tab',{name:'空间共享',exact:true}).click();
  await expect(page.getByRole('button',{name:'预览信泰项目参考.png',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'上传素材',exact:true}).first().click();
  await page.locator('input[type=file]').setInputFiles({name:'信泰专用共享.png',mimeType:'image/png',buffer:pixel});
  await expect(page.getByText('已添加',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'完成',exact:true}).click();
  await expect(page.getByRole('button',{name:'预览信泰专用共享.png',exact:true})).toBeVisible();
  await space(page, '东莞博物馆');
  await expect(page.getByRole('button', { name: '预览信泰专用共享.png', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '预览信泰项目参考.png', exact: true })).toHaveCount(0);
  await page.getByRole('tab',{name:'我的素材',exact:true}).click();
  await expect(page.getByRole('button',{name:'预览信泰项目参考.png',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'预览信泰专用共享.png',exact:true})).toHaveCount(0);
  await page.goto('/#/community?tab=assets');
  await page.locator('.res-assets-grid .res-cover-button').first().click();
  await page.getByRole('button', { name: '加入素材库', exact: true }).click();
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('zhichuang-studio-v1')!).state);
  const personal=state.assets.find((asset:{name:string;workspaceId:string})=>asset.name==='信泰项目参考.png'&&asset.workspaceId==='personal');
  const shared=state.assets.find((asset:{name:string;workspaceId:string})=>asset.name==='信泰项目参考.png'&&asset.workspaceId==='xintai');
  expect(personal).toBeTruthy();expect(shared.id).not.toBe(personal.id);
  expect(shared.origin.assetId).toBe(personal.id);expect(shared.origin.version).toBeTruthy();
  expect(shared.src).toBe(personal.src);expect(shared.package).toEqual(personal.package);
  expect(state.assets.find((asset:{name:string})=>asset.name==='信泰专用共享.png').workspaceId).toBe('xintai');
  const copy = state.assets.find((asset: { source: string; public: boolean }) => asset.source === 'community' && !asset.public);
  expect(copy.workspaceId).toBe('personal');
  expect(copy.origin?.assetId).toBeTruthy();expect(copy.origin?.version).toBeTruthy();
  await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
  await page.goto('/#/library?scope=mine');
  await expect(page.getByRole('button', { name: `预览${copy.name}`, exact: true })).toBeVisible();
  await reloadAndReopen(page);
  await expect(page.getByRole('button', { name: '切换创作空间' })).toContainText('东莞博物馆');
  await space(page, '信泰企业展厅');
  await expect(page.getByRole('button', { name: '预览信泰项目参考.png', exact: true })).toBeVisible();
  await page.getByRole('tab',{name:'空间共享',exact:true}).click();
  await expect(page.getByRole('button',{name:'预览信泰专用共享.png',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'预览信泰项目参考.png',exact:true})).toBeVisible();
  await reloadAndReopen(page);
  await expect(page.getByRole('button',{name:'预览信泰专用共享.png',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
